  const BadgeDef({
    required this.id,
    required this.shape,
    required this.big,
    required this.unit,
    required this.name,
    required this.desc,
    required this.key,
    required this.goal,
  });

  /// Short form for the long list below.
  const BadgeDef.of(this.id, this.shape, this.big, this.unit, this.name, this.desc, this.key, this.goal);

  final String id;
  final BadgeShape shape;
  final String big;
  final String unit;
  final String name;
  final String desc;

  /// Stats counter this badge reads.
  final String key;
  final int goal;
}


// Every exercise Bolt knows: what it trains, sensible starting numbers and
// how to do it. Templates, the muscle builder, the exercise picker and Learn
// all read from here.

class ExInfo {
  const ExInfo(
    this.name,
    this.muscle,
    this.sets,
    this.reps,
    this.load, {
    this.compound = false,
    this.area,
    this.alt,
    required this.works,
    required this.cues,
    required this.avoid,
  });

  final String name;

  /// Main muscle, a key of `kMuscles`, or `mobility`.
  final String muscle;
  final int sets;
  final String reps;
  final String load;

  /// Multi-joint lift: goes first when a workout is built.
  final bool compound;

  /// Injury area this exercise loads, if any.
  final String? area;

  /// Safer alternative when [area] is flagged.
  final String? alt;

  /// Muscles worked, for Learn.
  final String works;
  final List<String> cues;

  /// Common mistake.
  final String avoid;
}

